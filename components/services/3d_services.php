                                              <b>Character Rigging:</b><br>
                                              <ul>
                                                 <li>Creating advanced and customized rigs for 3D characters, enabling realistic movement and animation.</li>
                                                 <li>Rigging characters with bones, joints, and controllers to control various body parts like limbs, facial expressions, and deformations.</li>
                                                 </ul><br>

                                                 <b>Prop Rigging:</b><br>
                                                 <ul>
                                                 <li>Rigging 3D props or objects to add functionality and flexibility for animation purposes.</li>
                                                 <li>Creating control systems to manipulate and animate prop movements realistically.</li>
                                                 </ul><br>

                                                 <b>Joint Placement:</b><br>
                                                 <ul>
                                                 <li>Placing joints strategically to ensure smooth and natural movement of characters or objects during animation.</li>
                                                 </ul><br>

                                                 <b>Inverse Kinematics (IK):</b><br>
                                                 <ul>
                                                 <li>Implementing inverse kinematics to make character animations more intuitive and efficient, especially for limbs and joints.</li>
                                                 </ul><br>

                                                 <b>Forward Kinematics (FK):</b><br>
                                                 <ul>
                                                 <li>Setting up forward kinematics for animating character movements by directly manipulating the controllers.</li>
                                                 </ul><br>

                                                 <b>Blendshapes and Morph Targets:</b><br>
                                                 <ul>
                                                 <li>Creating blendshapes or morph targets for facial expressions and character deformations.</li>
                                                 </ul><br>

                                                 <b>Skinning and Weight Painting:</b><br>
                                                 <ul>
                                                 <li>Assigning weights to the mesh vertices to control their influence on the joints and achieve proper deformation during animation.</li>
                                                 </ul><br>

                                                 <b>Controllers and Constraints:</b><br>
                                                 <ul>
                                                 <li>Creating custom controllers and applying constraints to limit the range of motion and maintain natural movement.</li>
                                                 </ul><br>

                                                 <b>Rigging for Facial Animation:</b><br>
                                                 <ul>
                                                 <li>Rigging facial features, like eyes, mouth, and eyebrows, to enable expressive facial animation.</li>
                                                 </ul><br>

                                                 <b>Rigging for Deformations:</b><br>
                                                 <ul>
                                                 <li>Rigging characters for complex deformations, such as muscles, cloth, or hair, to achieve realistic animations.</li>
                                                 </ul><br>

                                                 <b>Rigging for Props and Vehicles:</b><br>
                                                 <ul>
